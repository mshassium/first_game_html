package com.first.game.net

/**
 * Разделение сохранённых настроек между копиями игры на одной машине.
 *
 * Обычно суффикс пустой. Он нужен, когда на одном компьютере запускают два окна
 * и хотят, чтобы это были разные игроки: анонимный вход хранится в настройках,
 * и без разделения второе окно оказалось бы тем же самым человеком.
 */
object AppProfile {

    var suffix: String = ""

    /** Имя набора настроек с учётом профиля. */
    fun prefsName(base: String): String = if (suffix.isEmpty()) base else "$base-$suffix"
}
