package com.first.game.ui

/**
 * Экранная клавиатура платформы.
 *
 * Ещё одно место, которое приходится писать под каждую платформу. На Android и
 * iOS клавиатуру показывает сама libGDX, а веб-бэкенд TeaVM её не показывает
 * вовсе: `setOnscreenKeyboardVisible` там пустой метод. На телефоне в браузере
 * это выглядит так, будто игра сломана — поле с золотым курсором есть, а
 * набрать в него нечего.
 *
 * Игре отдаётся набранная строка целиком, а не отдельные нажатия: мобильные
 * клавиатуры правят слово подсказкой, автозаменой и диктовкой, и посимвольного
 * потока от них не добиться.
 */
interface SoftKeyboard {

    /**
     * Показать клавиатуру и начать ввод со значения [initial].
     *
     * Зовётся только из обработчика касания: клавиатуру браузер открывает лишь
     * в ответ на жест игрока, из игрового цикла запрос молча отклоняется.
     */
    fun open(initial: String, maxLength: Int, secret: Boolean)

    /** Убрать клавиатуру. */
    fun close()

    /**
     * Какую долю экрана снизу закрыла клавиатура: 0 — не закрыла ничего.
     * Под неё поднимается окно ввода, иначе игрок печатает вслепую.
     */
    val coveredFraction: Float

    /** Набранный текст, если игрок менял его с прошлого опроса, иначе null. */
    fun poll(): String?

    /** Игрок нажал «Готово» — форму пора подтверждать. */
    fun pollSubmit(): Boolean
}

/**
 * Откуда игра берёт клавиатуру. Лаунчер платформы кладёт сюда свою реализацию;
 * там, где libGDX справляется сама, поле остаётся пустым и ввод идёт обычным
 * путём — через события клавиш.
 */
object SoftKeyboards {
    var instance: SoftKeyboard? = null
}
